import { leumiCategoryToOurs } from '../../src/import/categories';

test.each([
  ['מזון וצריכה', 'סופר'],
  ['מסעדות, קפה וברים', 'אוכל בחוץ'],
  ['תחבורה ורכבים', 'דלק ותחבורה'],
  ['דלק, חשמל וגז', 'דלק ותחבורה'],
  ['רפואה ובתי מרקחת', 'בריאות'],
  ['פנאי, בידור וספורט', 'פנאי'],
  ['טיסות ותיירות', 'פנאי'],
  ['אופנה', 'קניות'],
  ['ציוד ומשרד', 'קניות'],
  ['מוצרי חשמל', 'קניות'],
  ['עיצוב הבית', 'בית'],
  ['ביטוח', 'בית'],
  ['עירייה וממשלה', 'בית'],
  ['שירותי תקשורת', 'בית'],
  ['קוסמטיקה וטיפוח', 'קניות'],
  ['שונות', 'אחר'],
  [' מזון וצריכה ', 'סופר'],
])('%s → %s', (leumi, ours) => {
  expect(leumiCategoryToOurs(leumi)).toBe(ours);
});

test('null → אחר', () => {
  expect(leumiCategoryToOurs(null)).toBe('אחר');
});
